"""Read signing key inputs without exposing configured values."""
import hmac
import os
from pathlib import Path
import re
import stat


def signing_key_value(name):
    value = os.environ.get(name, "")
    location = os.environ.get(f"{name}_FILE")
    if not location:
        return value
    if value:
        raise RuntimeError(f"Configure either {name} or {name}_FILE.")
    try:
        path = Path(location)
        if not path.is_absolute() or path.is_symlink():
            raise OSError
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0))
        with os.fdopen(fd, "rb") as stream:
            info = os.fstat(stream.fileno())
            if not stat.S_ISREG(info.st_mode) or (
                os.name == "posix" and (info.st_uid != os.geteuid() or info.st_mode & 0o077)
            ):
                raise OSError
            data = stream.read(4097)
            if len(data) > 4096:
                raise OSError
            return data.decode("utf-8").removesuffix("\n").removesuffix("\r")
    except (OSError, UnicodeError):
        raise RuntimeError(f"{name}_FILE must be a private, readable regular file.") from None


def application_signing_key():
    value = signing_key_value("SECRET_KEY")
    if not re.fullmatch(r"[0-9a-fA-F]{64}", value):
        raise RuntimeError("SECRET_KEY must contain 32 randomly generated bytes encoded as 64 hex characters.")
    material = bytes.fromhex(value)
    if len(set(material)) < 16 or all(
        (current - previous) % 256 == (material[1] - material[0]) % 256
        for previous, current in zip(material, material[1:])
    ):
        raise RuntimeError("SECRET_KEY must be generated with a cryptographically secure random generator.")
    sso_key = signing_key_value("SSO_SECRET_KEY")
    if hmac.compare_digest(value.encode(), sso_key.strip().encode()):
        raise RuntimeError("SECRET_KEY and SSO_SECRET_KEY must be independent.")
    return value
